import { chromium } from '@playwright/test';
const [url, out] = process.argv.slice(2);
const browser = await chromium.launch({ channel: 'chrome', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const ctx = await browser.newContext({ viewport: { width: 393, height: 852 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
const errs = []; page.on('pageerror', (e) => errs.push(e.message));
await page.goto(url);
await page.waitForSelector('[data-testid=money]');
await page.waitForTimeout(800);
await page.evaluate(() => {
  const cc = window.__cc; const st = cc.store;
  cc.give(5e9);
  for (let f = 1; f < 5; f++) st.unlock(f);
  st.hire('floor', 'f0'); st.hire('floor', 'f3'); st.hire('lift', 'lift'); st.hire('ship', 'ship');
  for (const id of ['f0','f1','f2','f3','f4','lift','ship']) for (let k = 0; k < 4; k++) st.buy(id, 25);
  st.state.stats.totalEarned = st.state.stats.totalEarned.add(9.2e8);
  st.notify(true);
});
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/p1-topbar.png` });
await page.click('[data-testid=crown-btn]');
await page.waitForTimeout(900);
await page.screenshot({ path: `${out}/p2-sheet.png` });
await page.evaluate(() => document.querySelector('.sheet-body')?.scrollTo(0, 9999));
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/p3-sheet-bottom.png` });
await page.click('[data-testid=sell-brand]');
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/p4-confirm.png` });
await page.click('[data-testid=sell-brand]');
await page.waitForTimeout(1200);
await page.screenshot({ path: `${out}/p5-sold.png` });
await page.click('[data-testid=brand-sold-ok]');
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/p6-after.png` });
const st = await page.evaluate(() => { const s = window.__cc.store.state; return { crowns: s.prestige.crowns, runs: s.prestige.runs, floors: s.floors.filter((f) => f.unlocked).length, money: s.money.toString(), mgr: s.managers.map((m) => `${m.assignedTo}/${m.home}`) }; });
console.log(JSON.stringify(st), errs);
await browser.close();
