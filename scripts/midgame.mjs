// Dev helper: jump to a mid-game state and capture the tower at several scroll positions.
import { chromium } from '@playwright/test';
const url = process.argv[2] ?? 'http://localhost:4173/?debug=1';
const out = process.argv[3] ?? '/tmp/shots';
const w = Number(process.argv[4] ?? 390), h = Number(process.argv[5] ?? 844);
const browser = await chromium.launch({ channel: 'chrome', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const ctx = await browser.newContext({ viewport: { width: w, height: h }, deviceScaleFactor: 2, isMobile: w < 800, hasTouch: w < 800 });
const page = await ctx.newPage();
const logs = [];
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`));
await page.goto(url);
await page.waitForTimeout(1500);
await page.evaluate(() => {
  const cc = window.__cc; const st = cc.store;
  cc.give(1e12);
  for (let i = 1; i < 5; i++) st.unlock(i);
  const ids = ['f0','f1','f2','f3','f4'];
  for (const id of ids) st.hire('floor', id);
  st.hire('lift', 'lift'); st.hire('ship', 'ship');
  const lv = { f0: 99, f1: 74, f2: 49, f3: 24, f4: 9 };
  for (const id of ids) for (let k = 0; k < lv[id]; k++) st.buy(id, 1);
  for (let k = 0; k < 60; k++) st.buy('lift', 1);
  for (let k = 0; k < 55; k++) st.buy('ship', 1);
  st.state.quest.index = 8;
  st.notify(true);
});
await page.waitForTimeout(500);
await page.keyboard.press('Escape');
await page.waitForTimeout(1000);
await page.evaluate(() => { const w = window.__cc.world; w.scrollTarget = w.bounds().max; });
await page.waitForTimeout(5000);
await page.screenshot({ path: `${out}/m1-bottom.png` });
await page.evaluate(() => window.__cc.focus('f2'));
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/m2-middle.png` });
await page.evaluate(() => window.__cc.focus('f4'));
await page.waitForTimeout(400);
await page.evaluate(() => { const w = window.__cc.world; w.scrollTarget = w.bounds().min; });
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/m3-top.png` });
console.log(logs.join('\n'));
await browser.close();
