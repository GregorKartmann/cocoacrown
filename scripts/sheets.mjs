import { chromium } from '@playwright/test';
const url = process.argv[2]; const out = process.argv[3];
const browser = await chromium.launch({ channel: 'chrome', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
const logs = [];
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`));
page.on('console', (m) => { if (m.type() === 'error') logs.push(`[console] ${m.text()}`); });
await page.goto(url);
await page.waitForTimeout(1500);
await page.evaluate(() => {
  const cc = window.__cc; const st = cc.store;
  cc.give(5e6);
  st.unlock(1);
  st.hire('floor', 'f0'); st.hire('floor', 'f1'); st.hire('lift', 'lift'); st.hire('ship', 'ship');
  for (let k = 0; k < 6; k++) st.hire('floor', null);
  for (let k = 0; k < 24; k++) { st.buy('f0', 1); st.buy('lift', 1); st.buy('ship', 1); }
});
await page.waitForTimeout(800);
// open station sheet for floor 0 via its badge position
const pos = await page.evaluate(() => window.__cc.positions());
console.log(JSON.stringify(Object.keys(pos)));
await page.evaluate(() => window.__cc.focus('f0'));
await page.waitForTimeout(900);
const p2 = await page.evaluate(() => window.__cc.positions());
await page.touchscreen.tap(p2.f0badge.x, p2.f0badge.y);
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/s1-station.png` });
await page.keyboard.press('Escape');
await page.waitForTimeout(400);
await page.click('[data-testid=nav-managers]');
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/s2-managers.png` });
await page.click('[data-testid=hire]').catch(() => {});
await page.waitForTimeout(900);
await page.screenshot({ path: `${out}/s2b-reveal.png` });
await page.mouse.click(10, 400);
await page.waitForTimeout(500);
await page.keyboard.press('Escape');
await page.waitForTimeout(400);
await page.click('text=Aufträge');
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/s3-quests.png` });
await page.keyboard.press('Escape');
await page.waitForTimeout(400);
await page.click('text=Statistik');
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/s4-stats.png` });
console.log(logs.join('\n'));
await browser.close();
